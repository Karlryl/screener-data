'use strict';

// Pure text parser. No I/O, no vendor-growth matching, no fallback to another income line.
// pdftotext -layout may lose the Chinese glyphs. Two independent amount anchors identify
// the operating-revenue row and its scale; column geometry is only used AFTER both match.
const VERSION = 'cn-q3-layout-v2';
const finite = Number.isFinite;
const amountPattern = /^-?\d{1,3}(?:,\d{3})+(?:\.\d{1,2})?$/;
const epsilon = n => Math.max(1e-7, Math.abs(n) * Number.EPSILON * 8);
const half = s => 0.5 * 10 ** -(s.split('.')[1]?.length || 0);
const number = s => Number(s.replace(/,/g, '').replace(/%$/, ''));
const inside = (v, lo, hi) => finite(v) && v >= lo - epsilon(lo) && v <= hi + epsilon(hi);

// Value-blind row templates for the supported Q3 text extractions. A template
// records the row indices (including wrapped cells) of the first four quarter/YTD
// amount cells and standalone percent headers, never tickers or financial values.
// Where those tracks collide, column extents distinguish the staggered layout.
// Glyph loss makes free-form row inference unsafe: an unknown template is a named
// gap. Extending this finite grammar requires positive and erased-cell fixtures.
// These templates were measured on the cached Q3 corpus and existing real fixtures;
// they are recognition evidence, not an independent out-of-sample accuracy test.
function rowShape(lines, amounts, q, y, left, lo) {
  const origin = Math.min(q.row, y.row);
  const track = a => amounts.filter(t => t.row >= a.row && t.row <= origin + 14 && t.x <= a.end && t.end > a.x)
    .slice(0, 4).map(t => [t.row - origin, t.endRow - origin]);
  const headers = lines.slice(lo, origin + 9).flatMap((s, i) => /^\s*\(?%\)?\s*$/.test(s.slice(left, y.x)) ? [i + lo - origin] : []);
  return JSON.stringify([track(q), track(y), headers]);
}

